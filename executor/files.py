"""
File/folder operations. Pure deterministic execution layer - by design,
this module has NO awareness of voice, gestures, or LLMs. It only accepts
already-resolved, validated inputs (typically an Intent + resolved Path).
This keeps it independently testable and swappable.
"""

from __future__ import annotations
import re
from pathlib import Path
from typing import Optional
from dataclasses import dataclass
from loguru import logger

try:
    from send2trash import send2trash
    _HAVE_SEND2TRASH = True
except ImportError:
    _HAVE_SEND2TRASH = False
    logger.warning("send2trash not installed - deletes will be PERMANENT. `pip install send2trash`.")

from executor.paths import resolve_folder, ensure_unique_path, find_file_anywhere, sanitize_filename

# Minimal starter boilerplate per extension, so "create a python file" produces
# something a little more useful than a completely empty file.
_TEMPLATES = {
    "py": '"""Generated by AI Desktop Assistant."""\n\n\ndef main():\n    pass\n\n\nif __name__ == "__main__":\n    main()\n',
    "md": "# {title}\n",
    "txt": "",
    "html": "<!DOCTYPE html>\n<html>\n<head><title>{title}</title></head>\n<body>\n</body>\n</html>\n",
    "java": "public class {class_name} {{\n    public static void main(String[] args) {{\n\n    }}\n}}\n",
}


@dataclass
class ExecResult:
    success: bool
    message: str
    path: Optional[Path] = None


def create_file(name: str | None, extension: str | None, target_folder_name: str | None = None) -> ExecResult:
    if not name or not extension:
        return ExecResult(False, "Missing file name or extension.")

    clean_name = sanitize_filename(name)
    folder = resolve_folder(target_folder_name)
    folder.mkdir(parents=True, exist_ok=True)

    filename = clean_name if clean_name.endswith(f".{extension}") else f"{clean_name}.{extension}"
    path = ensure_unique_path(folder / filename)

    template = _TEMPLATES.get(extension, "")
    if "{class_name}" in template:
        # Java convention: public class name must match the filename.
        class_name = "".join(w.capitalize() for w in re.split(r"[\s_\-]+", clean_name) if w) or "Main"
        content = template.format(class_name=class_name)
    elif "{title}" in template:
        content = template.format(title=clean_name)
    else:
        content = template

    path.write_text(content, encoding="utf-8")
    logger.info(f"Created file {path}")
    return ExecResult(True, f"Created {path.name} in {folder.name}", path)


def create_folder(name: str | None, parent_folder_name: str | None = None) -> ExecResult:
    if not name:
        return ExecResult(False, "Missing folder name.")

    clean_name = sanitize_filename(name)
    parent = resolve_folder(parent_folder_name)
    path = parent / clean_name
    if path.exists():
        return ExecResult(False, f"A folder named {clean_name} already exists in {parent.name}", path)
    path.mkdir(parents=True, exist_ok=False)
    logger.info(f"Created folder {path}")
    return ExecResult(True, f"Created folder {clean_name} in {parent.name}", path)


def delete_file(name: str | None, search_folder_name: str | None = None) -> ExecResult:
    if not name:
        return ExecResult(False, "Which file or folder would you like to delete?")

    clean_name = sanitize_filename(name)
    folder = resolve_folder(search_folder_name)

    exact = folder / clean_name
    if exact.exists():
        candidates = [exact]
    elif Path(clean_name).suffix:
        candidates = []  # had an extension but exact match not found - don't glob-guess
    else:
        # no extension given (e.g. deleting a folder, or a file named without
        # its extension) - fall back to a prefix search, but only as a last resort
        candidates = [c for c in folder.glob(f"{clean_name}*") if c.exists()]

    if not candidates and not search_folder_name:
        # User didn't say where it lives - don't give up at just the
        # default location; check Desktop/Documents/Downloads and a
        # shallow walk under home before reporting failure.
        candidates = find_file_anywhere(clean_name)

    if not candidates:
        if search_folder_name:
            return ExecResult(False, f"Couldn't find '{clean_name}' in {folder.name}")
        return ExecResult(False, f"Couldn't find '{clean_name}' in Desktop, Documents, or Downloads")
    if len(candidates) > 1:
        names = ", ".join(f"{c.name} ({c.parent.name})" for c in candidates)
        return ExecResult(False, f"Multiple matches for '{clean_name}': {names}. Please be more specific.")

    target = candidates[0]
    if _HAVE_SEND2TRASH:
        send2trash(str(target))
        logger.info(f"Sent to trash: {target}")
        return ExecResult(True, f"Moved {target.name} to trash", target)
    else:
        if target.is_dir():
            import shutil
            shutil.rmtree(target)
        else:
            target.unlink()
        logger.warning(f"Permanently deleted: {target}")
        return ExecResult(True, f"Permanently deleted {target.name}", target)


def rename_file(name: str | None, new_name: str | None, folder_name: str | None = None) -> ExecResult:
    if not name or not new_name:
        return ExecResult(False, "Missing original name or new name.")

    clean_name = sanitize_filename(name)
    clean_new_name = sanitize_filename(new_name)
    folder = resolve_folder(folder_name)
    matches = list(folder.glob(f"{clean_name}*"))

    if not matches and not folder_name:
        matches = find_file_anywhere(clean_name)

    if not matches:
        if folder_name:
            return ExecResult(False, f"Couldn't find '{clean_name}' in {folder.name}")
        return ExecResult(False, f"Couldn't find '{clean_name}' in Desktop, Documents, or Downloads")
    if len(matches) > 1:
        names = ", ".join(f"{c.name} ({c.parent.name})" for c in matches)
        return ExecResult(False, f"Multiple matches for '{clean_name}': {names}. Please be more specific.")
    src = matches[0]
    dst = ensure_unique_path(src.with_name(clean_new_name + src.suffix if not Path(clean_new_name).suffix else clean_new_name))
    src.rename(dst)
    logger.info(f"Renamed {src} -> {dst}")
    return ExecResult(True, f"Renamed to {dst.name}", dst)


def copy_file(name: str | None, destination_folder_name: str | None, source_folder_name: str | None = None) -> ExecResult:
    """
    BUG FIXED HERE: this used to always search `resolve_folder(None)` (the
    default create location, usually Desktop) for the source file no matter
    what - there was no way to say where a file was actually copying FROM.
    "copy resume.pdf to Documents" only ever worked if resume.pdf happened
    to be on the Desktop. `source_folder_name` (populated from phrasing
    like "copy resume.pdf from Downloads to Documents" - see
    intent/rules.py's _parse_copy) now actually gets used, and when no
    source is named at all this falls back to the same multi-location
    search delete/rename use.
    """
    if not name or not destination_folder_name:
        return ExecResult(False, "Missing file name or destination folder.")

    import shutil
    clean_name = sanitize_filename(name)
    src_folder = resolve_folder(source_folder_name)
    matches = [c for c in src_folder.glob(f"{clean_name}*") if c.exists()]

    if not matches and not source_folder_name:
        matches = find_file_anywhere(clean_name)

    if not matches:
        if source_folder_name:
            return ExecResult(False, f"Couldn't find '{clean_name}' in {src_folder.name}")
        return ExecResult(False, f"Couldn't find '{clean_name}' in Desktop, Documents, or Downloads")
    if len(matches) > 1:
        names = ", ".join(f"{c.name} ({c.parent.name})" for c in matches)
        return ExecResult(False, f"Multiple matches for '{clean_name}': {names}. Please be more specific.")

    src = matches[0]
    dest_folder = resolve_folder(destination_folder_name)
    dest_folder.mkdir(parents=True, exist_ok=True)
    dst = ensure_unique_path(dest_folder / src.name)
    shutil.copy2(src, dst)
    logger.info(f"Copied {src} -> {dst}")
    return ExecResult(True, f"Copied {src.name} to {dest_folder.name}", dst)